-- Menu categories (lookup) + a nullable category on menu, and a menu_updated_at audit column.

CREATE TABLE IF NOT EXISTS menu_category (
    menu_category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    menu_category_name VARCHAR(100) NOT NULL,
    CONSTRAINT pk__menu_category PRIMARY KEY (menu_category_id),
    CONSTRAINT uq__menu_category__name UNIQUE (menu_category_name)
);

ALTER TABLE menu ADD COLUMN menu_category_id INTEGER;
ALTER TABLE menu ADD COLUMN menu_updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW();

ALTER TABLE menu ADD CONSTRAINT fk__menu__menu_category_id
    FOREIGN KEY (menu_category_id) REFERENCES menu_category (menu_category_id) ON DELETE SET NULL;

CREATE INDEX idx__menu__menu_category_id ON menu (menu_category_id);

-- Seed a few categories and classify the existing seeded menu.
INSERT INTO menu_category (menu_category_name)
VALUES ('Food'), ('Drinks'), ('Desserts')
ON CONFLICT (menu_category_name) DO NOTHING;

UPDATE menu
SET menu_category_id = (SELECT menu_category_id FROM menu_category WHERE menu_category_name = 'Food')
WHERE menu_name = 'Main Menu' AND menu_category_id IS NULL;
