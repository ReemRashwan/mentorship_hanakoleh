-- Menu change history (audit). Denormalized restaurant_id + menu_name snapshot so that
-- audit rows survive even if a menu is later renamed or deleted.

CREATE TABLE IF NOT EXISTS menu_history (
    menu_history_id     BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    restaurant_id       INTEGER     NOT NULL,
    menu_id             INTEGER,
    menu_name           VARCHAR(150) NOT NULL,
    change_type         VARCHAR(20) NOT NULL,
    changed_by_user_id  INTEGER,
    changed_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    notes               VARCHAR(500),
    CONSTRAINT pk__menu_history PRIMARY KEY (menu_history_id),
    CONSTRAINT fk__menu_history__restaurant_id
        FOREIGN KEY (restaurant_id) REFERENCES restaurant (restaurant_id) ON DELETE CASCADE,
    CONSTRAINT fk__menu_history__menu_id
        FOREIGN KEY (menu_id) REFERENCES menu (menu_id) ON DELETE SET NULL,
    CONSTRAINT fk__menu_history__changed_by_user_id
        FOREIGN KEY (changed_by_user_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT chk__menu_history__change_type
        CHECK (change_type IN ('CREATED', 'UPDATED', 'DISABLED', 'DELETED'))
);

-- Primary access path: a restaurant's history, newest first (optionally scoped to one menu).
CREATE INDEX idx__menu_history__restaurant_id_changed_at ON menu_history (restaurant_id, changed_at);
CREATE INDEX idx__menu_history__menu_id ON menu_history (menu_id);

