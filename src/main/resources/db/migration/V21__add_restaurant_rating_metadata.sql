-- Top-rated discovery: cached review count + a restaurant category (cuisine) lookup.
-- Rating uses the existing cached restaurant.restaurant_rating (no review table yet).

ALTER TABLE restaurant ADD COLUMN restaurant_review_count INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS restaurant_category (
    restaurant_category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    restaurant_category_name VARCHAR(100) NOT NULL,
    CONSTRAINT pk__restaurant_category PRIMARY KEY (restaurant_category_id),
    CONSTRAINT uq__restaurant_category__name UNIQUE (restaurant_category_name)
);

ALTER TABLE restaurant ADD COLUMN restaurant_category_id INTEGER;
ALTER TABLE restaurant ADD CONSTRAINT fk__restaurant__restaurant_category_id
    FOREIGN KEY (restaurant_category_id) REFERENCES restaurant_category (restaurant_category_id) ON DELETE SET NULL;
CREATE INDEX idx__restaurant__restaurant_category_id ON restaurant (restaurant_category_id);

-- Seed categories.
INSERT INTO restaurant_category (restaurant_category_name)
VALUES ('Egyptian'), ('Fast Food'), ('Desserts'), ('Beverages')
ON CONFLICT (restaurant_category_name) DO NOTHING;

-- Classify the existing seeded restaurant and give it a review count.
UPDATE restaurant
SET restaurant_category_id =
        (SELECT restaurant_category_id FROM restaurant_category WHERE restaurant_category_name = 'Egyptian'),
    restaurant_review_count = 120
WHERE restaurant_name = 'Koshary El Tahrir';

